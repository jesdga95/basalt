const struct ggml_type_traits* ggml_get_type_traits(enum ggml_type type) {
    if ((int) type < 0 || (int) type >= GGML_TYPE_COUNT || type_traits[type].type_name == NULL) return NULL;
    return &type_traits[type];
}

int64_t ggml_blck_size(enum ggml_type type) {
    const struct ggml_type_traits* t = ggml_get_type_traits(type);
    return t ? t->blck_size : 0;
}

size_t ggml_type_size(enum ggml_type type) {
    const struct ggml_type_traits* t = ggml_get_type_traits(type);
    return t ? t->type_size : 0;
}

size_t ggml_row_size(enum ggml_type type, int64_t ne) {
    const struct ggml_type_traits* t = ggml_get_type_traits(type);
    if (t == NULL) return 0;
    assert(ne % t->blck_size == 0);
    return t->type_size * ne / t->blck_size;
}

const char* ggml_type_name(enum ggml_type type) {
    const struct ggml_type_traits* t = ggml_get_type_traits(type);
    return t ? t->type_name : NULL;
}

size_t ggml_quantize_chunk(enum ggml_type type, const float* src, void* dst, int64_t start, int64_t nrows,
                           int64_t n_per_row) {
    const struct ggml_type_traits* t = ggml_get_type_traits(type);
    if (t == NULL || t->from_float_ref == NULL) return 0;
    GGML_ASSERT(start % t->blck_size == 0);
    GGML_ASSERT(start % n_per_row == 0);
    const size_t row_size = ggml_row_size(type, n_per_row);
    t->from_float_ref(src + start, (char*) dst + (size_t) (start / n_per_row) * row_size, nrows * n_per_row);
    return nrows * row_size;
}
